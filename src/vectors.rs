#[derive(Debug, Clone, Copy)]
pub struct Normal<T>(T);

impl<T: Normalize> Normal<T> {
    pub fn new(v: T) -> Normal<T> {
        Normal(v.normalized())
    }
}

impl<T> std::ops::Deref for Normal<T> {
    type Target = T;

    fn deref(&self) -> &Self::Target {
        &self.0
    }
}
